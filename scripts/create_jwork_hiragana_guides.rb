def upsert_article!(spec)
  parent = Column.find_by(code: spec[:parent_code])
  raise "parent missing: #{spec[:parent_code]}" unless parent

  parent.update!(cluster_limit: [parent.cluster_limit.to_i, parent.children.count + 5].max)

  column = Column.find_or_initialize_by(code: spec[:code])
  column.assign_attributes(
    title: spec[:title],
    keyword: spec[:keyword],
    description: spec[:description],
    body: spec[:body].strip,
    article_type: "child",
    parent_id: parent.id,
    genre: parent.genre,
    sub_genre: spec[:sub_genre],
    language: "hiragana",
    status: "completed",
    generation_status: "completed",
    client_id: parent.client_id,
    published_at: Time.current
  )
  column.save!
  column
end

puts "LANGUAGES=#{Column::LANGUAGES.inspect}"
raise "hiragana language is not enabled on this deploy" unless Column::LANGUAGES.include?("hiragana")

