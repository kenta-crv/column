def upsert_service_genre!(attrs)
  genre = ServiceGenre.find_or_initialize_by(client_id: nil, key: attrs.fetch(:key))
  genre.assign_attributes(attrs.except(:key))
  genre.save!
  puts "ServiceGenre: #{genre.key} (#{genre.ja})"
end

